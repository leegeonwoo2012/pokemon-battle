import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { join } from 'node:path';

// PokéAPI's Pokémon endpoint maps a form name to its actual sprite URLs.
const forms = JSON.parse(await readFile(join(process.cwd(),'src','data','form-slugs.generated.json'),'utf8'));
const output = join(process.cwd(), 'public', 'sprites', 'forms');
const manifestPath=join(output,'manifest.json');
const previous=existsSync(manifestPath)?JSON.parse(await readFile(manifestPath,'utf8')):{};
const manifest = {};
const pngSignature = Buffer.from('89504e470d0a1a0a', 'hex');
const validAsset = (bytes, contentType) => contentType === 'image/png'
  ? bytes.length >= 24 && bytes.subarray(0, 8).equals(pngSignature)
  : contentType === 'image/webp' && bytes.length >= 30 && bytes.toString('ascii', 0, 4) === 'RIFF' && bytes.toString('ascii', 8, 12) === 'WEBP';
const dimensions = (bytes, contentType) => {
  if(contentType==='image/png')return {width:bytes.readUInt32BE(16),height:bytes.readUInt32BE(20)};
  let offset=12;
  while(offset+8<=bytes.length){
    const kind=bytes.toString('ascii',offset,offset+4),length=bytes.readUInt32LE(offset+4),start=offset+8;
    if(kind==='VP8X'&&length>=10)return {width:1+bytes.readUIntLE(start+4,3),height:1+bytes.readUIntLE(start+7,3)};
    offset=start+length+(length&1);
  }
  return {width:0,height:0};
};
const filePath=(id,facing,entry)=>join(output,`${id}-${facing}.${entry?.format??'png'}`);

async function get(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(20_000) });
  if (!response.ok) throw Error(`${response.status} ${url}`);
  return response;
}

for (const [id, slug] of Object.entries(forms)) {
  if(previous[id]?.slug===slug&&['front','back'].every(facing=>existsSync(filePath(id,facing,previous[id])))){manifest[id]=previous[id];continue;}
  try {
    const data = await (await get(`https://pokeapi.co/api/v2/pokemon/${slug}`)).json();
    if (data.name !== slug || !Number.isInteger(data.id)) throw Error('form identity mismatch');
    const entry = { id: data.id, slug, front: null, back: null, format:'png' };
    for (const facing of ['front', 'back']) {
      // Legends: Z-A's Mega Zygarde is indexed by PokéAPI but its regular
      // front_default/back_default and Showdown sprite slots are empty.
      const source = data.sprites[`${facing}_default`]
        ?? (slug==='zygarde-mega' ? data.sprites.versions?.['generation-ix']?.['legends-za']?.[`${facing}_default`] : undefined);
      if (!source) throw Error(`${facing} URL missing`);
      const response = await get(source);
      const bytes = Buffer.from(await response.arrayBuffer());
      const contentType=(response.headers.get('content-type')??'').split(';')[0];
      if (!validAsset(bytes,contentType)) throw Error(`${facing} response is not a PNG or WebP image`);
      const {width,height}=dimensions(bytes,contentType);
      if (!width || !height || width > 2048 || height > 2048) throw Error(`${facing} dimensions invalid`);
      await mkdir(output, { recursive: true });
      const format=contentType==='image/webp'?'webp':'png';
      if(entry.format!==format&&facing==='back')throw Error('front/back image formats differ');
      entry.format=format;
      await writeFile(filePath(id,facing,entry), bytes);
      entry[facing] = { source, width, height, bytes: bytes.length, contentType };
    }
    manifest[id] = entry;
    process.stdout.write(`${id}: front ${entry.front.width}x${entry.front.height}, back ${entry.back.width}x${entry.back.height}\n`);
  } catch (error) {
    process.stderr.write(`${id}: ${error.message}\n`);
    if(previous[id]&&['front','back'].every(facing=>existsSync(filePath(id,facing,previous[id]))))manifest[id]=previous[id];
  }
}
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(join(process.cwd(), 'src', 'data', 'form-sprites.generated.ts'),
  `// Verified local front/back pairs generated by scripts/acquire-form-sprites.mjs.\nexport const availableFormSprites = ${JSON.stringify(Object.keys(manifest), null, 2)} as const;\nexport const formSpriteFormats: Record<string,'png'|'webp'> = ${JSON.stringify(Object.fromEntries(Object.entries(manifest).map(([id,entry])=>[id,entry.format??'png'])),null,2)};\n`);
process.stdout.write(`Verified form pairs: ${Object.keys(manifest).length}/${Object.keys(forms).length}\n`);
if (Object.keys(manifest).length !== Object.keys(forms).length) process.exitCode = 1;
